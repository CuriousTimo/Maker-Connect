-- Machines, their jobs and files, and what a printer's files and transfers keep (crate::store, crate::link,
-- crate::devices::printer_files): today's tables and columns on Postgres (hub-core-v2.md §3, "Step 2's
-- tables"). Ids keep their types (INTEGER → bigint, text ids text); times are timestamptz through
-- at_unix()/unix_seconds() (20261118000000_roles.sql); JSON kept as text, so what is stored reads back
-- byte for byte. Every table carries space_id with row-level security on app_space(). A machine that
-- has not been paired yet has no space (space_id NULL): only the admin pool (agent and token lookups) sees it.
-- The columns of the farm (farm, sheet, service_every_h, serviced_at; jobs: part_id, per_plate, confirmed_*)
-- are today's columns of these tables; lane 4 moves the farm's own tables.

CREATE TABLE machines (
    id text PRIMARY KEY,
    space_id bigint REFERENCES spaces (id),
    name text NOT NULL,
    kind text NOT NULL,
    agent_version text NOT NULL,
    token text NOT NULL UNIQUE,
    pairing_code text,
    registered_at timestamptz NOT NULL,
    last_seen timestamptz,
    telemetry text,
    profile text,
    profile_chosen boolean NOT NULL DEFAULT false,
    link text NOT NULL DEFAULT 'agent',
    details text,
    mesh text,
    media text,
    powered_by text,
    power_channel integer,
    reached_through text,
    agent text,
    peer text,
    out_of_use text,
    out_of_use_at timestamptz,
    laser_w double precision,
    -- 0: open to every member; 1: needs permission; 2: needs training (crate::access).
    induction_required integer NOT NULL DEFAULT 0,
    -- Comma separated; empty: nothing; NULL: what its kind needs (crate::safety).
    ppe text,
    labels text,
    usb_print_by text,
    usb_print_at timestamptz,
    agent_update_to text,
    agent_update_at timestamptz,
    farm boolean NOT NULL DEFAULT false,
    sheet text,
    service_every_h double precision,
    serviced_at timestamptz,
    -- What other tables' keys point at: a machine with its space (20261118000310_machine_keys.sql).
    UNIQUE (id, space_id)
);
CREATE INDEX machines_by_space ON machines (space_id, name);
CREATE INDEX machines_by_pairing_code ON machines (pairing_code) WHERE pairing_code IS NOT NULL;

CREATE TABLE files (
    id text PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    name text NOT NULL,
    size bigint NOT NULL,
    uploaded_at timestamptz NOT NULL,
    meta text NOT NULL
);
CREATE INDEX files_by_space ON files (space_id, uploaded_at DESC);

-- A job outlives its machine and its file (the old space keeps its history), so no foreign keys.
CREATE TABLE jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    machine_id text NOT NULL,
    file_id text NOT NULL,
    file_name text NOT NULL,
    state text NOT NULL,
    created_at timestamptz NOT NULL,
    started_at timestamptz,
    ended_at timestamptz,
    reason text,
    from_line bigint,
    used double precision,
    spool_id bigint,
    restart_line bigint,
    taken_at timestamptz,
    by_name text,
    part_id bigint,
    per_plate bigint,
    confirmed_at timestamptz,
    confirmed_good bigint,
    confirmed_by text
);
CREATE INDEX jobs_by_machine ON jobs (machine_id, id DESC);
CREATE INDEX jobs_by_space ON jobs (space_id, ended_at);

-- What a printer's USB stick holds, as last read.
-- Its machine's, in the machine's space (a key on the id alone would let one space's row point at another
-- space's machine: a foreign key's check sees past row-level security); it moves with the machine.
CREATE TABLE printer_files (
    machine_id text NOT NULL,
    space_id bigint NOT NULL REFERENCES spaces (id),
    path text NOT NULL,
    data text,
    at timestamptz,
    asked_at timestamptz,
    PRIMARY KEY (machine_id, path),
    FOREIGN KEY (machine_id, space_id) REFERENCES machines (id, space_id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- A file on its way to a printer.
CREATE TABLE printer_transfers (
    iv text PRIMARY KEY,
    machine_id text NOT NULL,
    space_id bigint NOT NULL REFERENCES spaces (id),
    file_id text NOT NULL,
    key text NOT NULL,
    size bigint NOT NULL,
    path text NOT NULL,
    command_id bigint,
    job_id bigint,
    print_after boolean NOT NULL DEFAULT false,
    state text NOT NULL DEFAULT 'waiting',
    reason text,
    created_at timestamptz NOT NULL
);
CREATE INDEX printer_transfers_by_machine ON printer_transfers (machine_id, state);

ALTER TABLE machines ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON machines USING (space_id = app_space());
ALTER TABLE files ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON files USING (space_id = app_space());
ALTER TABLE jobs ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON jobs USING (space_id = app_space());
ALTER TABLE printer_files ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON printer_files USING (space_id = app_space());
ALTER TABLE printer_transfers ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON printer_transfers USING (space_id = app_space());
