-- Materials (crate::stock) and Spoolman's model beside it (crate::spoolman, crate::spoolmandb): today's
-- tables and columns on Postgres (hub-core-v2.md §3, "Step 2's tables"). Ids keep their types (INTEGER →
-- bigint, a location's code text); times are timestamptz through at_unix()/unix_seconds()
-- (store/migrations); a spool's `archived` is boolean; JSON (extra, definitions) kept as text, so what is
-- stored reads back byte for byte. Every table carries space_id with row-level security on app_space().
-- A reference to another tenant row is a key with its space, `(space_id, parent)` to the parent's
-- `UNIQUE (space_id, id)` (design decisions/20261119-composite-foreign-keys.md): a row never points into
-- another space. What a removal refuses (a vendor with filaments, a filament with spools) the code
-- checks first, as Spoolman does; the key is the wall behind it. `spool.location_id` is free text.

-- SQLite's rowid, as Spoolman on SQLite gives its ids (and these tables gave theirs): one past the highest
-- id in the table now, in any space, so the id of a row removed last is given again. Owner's rights, so
-- row-level security does not hide another space's ids; one at a time per table until the transaction ends.
CREATE FUNCTION next_rowid(t text) RETURNS bigint LANGUAGE plpgsql VOLATILE SECURITY DEFINER
    SET search_path = public AS $$
DECLARE
    n bigint;
BEGIN
    IF t NOT IN ('vendor', 'filament', 'spool', 'tag') THEN
        RAISE EXCEPTION 'next_rowid: not for %', t;
    END IF;
    PERFORM pg_advisory_xact_lock(hashtext('next_rowid:' || t)::bigint);
    EXECUTE format('SELECT COALESCE(max(id), 0) + 1 FROM %I', t) INTO n;
    RETURN n;
END $$;

-- Keyed per space: the codes people see (L-0001) are a space's own, so one space's never block or
-- reveal another's.
CREATE TABLE locations (
    id text NOT NULL,
    space_id bigint NOT NULL REFERENCES spaces (id),
    name text NOT NULL,
    parent text,
    slots bigint,
    model text,
    description text,
    PRIMARY KEY (space_id, id),
    FOREIGN KEY (space_id, parent) REFERENCES locations (space_id, id)
);

CREATE TABLE movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    item text NOT NULL,
    kind text NOT NULL,
    amount double precision,
    place text,
    note text,
    at timestamptz NOT NULL
);
CREATE INDEX movements_by_item ON movements (space_id, item, id DESC);

-- Spoolman's settings, per space.
CREATE TABLE setting (
    space_id bigint NOT NULL REFERENCES spaces (id),
    key text NOT NULL,
    value text NOT NULL,
    last_updated timestamptz NOT NULL,
    PRIMARY KEY (space_id, key)
);

CREATE TABLE vendor (
    id bigint PRIMARY KEY DEFAULT next_rowid('vendor'),
    space_id bigint NOT NULL REFERENCES spaces (id),
    registered timestamptz NOT NULL,
    name text NOT NULL,
    empty_spool_weight double precision,
    comment text,
    external_id text,
    extra text NOT NULL DEFAULT '{}',
    UNIQUE (space_id, id)
);

CREATE TABLE filament (
    id bigint PRIMARY KEY DEFAULT next_rowid('filament'),
    space_id bigint NOT NULL REFERENCES spaces (id),
    registered timestamptz NOT NULL,
    name text,
    vendor_id bigint,
    material text,
    price double precision,
    density double precision NOT NULL DEFAULT 1.24,
    diameter double precision NOT NULL DEFAULT 1.75,
    weight double precision,
    spool_weight double precision,
    article_number text,
    comment text,
    settings_extruder_temp bigint,
    settings_bed_temp bigint,
    color_hex text,
    multi_color_hexes text,
    multi_color_direction text,
    external_id text,
    extra text NOT NULL DEFAULT '{}',
    -- Maker Connect's own, beside Spoolman's:
    kind text NOT NULL DEFAULT 'filament',
    unit text NOT NULL DEFAULT 'g',
    color_name text,
    ink text,
    media text,
    width_mm bigint,
    minimum bigint,
    UNIQUE (space_id, id),
    FOREIGN KEY (space_id, vendor_id) REFERENCES vendor (space_id, id)
);

CREATE TABLE spool (
    id bigint PRIMARY KEY DEFAULT next_rowid('spool'),
    space_id bigint NOT NULL REFERENCES spaces (id),
    registered timestamptz NOT NULL,
    first_used timestamptz,
    last_used timestamptz,
    price double precision,
    filament_id bigint NOT NULL,
    initial_weight double precision,
    spool_weight double precision,
    used_weight double precision NOT NULL DEFAULT 0,
    location_id text,
    lot_nr text,
    comment text,
    archived boolean NOT NULL DEFAULT false,
    extra text NOT NULL DEFAULT '{}',
    -- Maker Connect's own: the machine it is loaded in, and its slot in a dry box.
    machine text,
    slot bigint,
    UNIQUE (space_id, id),
    FOREIGN KEY (space_id, filament_id) REFERENCES filament (space_id, id),
    -- Loaded in a machine of its space; the machine removed or moved: no longer loaded.
    FOREIGN KEY (machine, space_id) REFERENCES machines (id, space_id) ON DELETE SET NULL (machine)
);
CREATE INDEX spool_by_machine ON spool (machine) WHERE machine IS NOT NULL;

-- NFC tags (Spoolman 0.27's): one physical tag means one spool or filament.
CREATE TABLE tag (
    id bigint PRIMARY KEY DEFAULT next_rowid('tag'),
    space_id bigint NOT NULL REFERENCES spaces (id),
    uid text NOT NULL,
    target_type text NOT NULL,
    spool_id bigint,
    filament_id bigint,
    target_value text,
    format text,
    added timestamptz NOT NULL,
    UNIQUE (space_id, uid),
    FOREIGN KEY (space_id, spool_id) REFERENCES spool (space_id, id) ON DELETE CASCADE,
    FOREIGN KEY (space_id, filament_id) REFERENCES filament (space_id, id) ON DELETE CASCADE
);

CREATE TABLE extra_field (
    space_id bigint NOT NULL REFERENCES spaces (id),
    entity_type text NOT NULL,
    key text NOT NULL,
    definition text NOT NULL,
    PRIMARY KEY (space_id, entity_type, key)
);

-- A job's spool: the job survives it.
ALTER TABLE jobs
    ADD CONSTRAINT jobs_spool FOREIGN KEY (space_id, spool_id) REFERENCES spool (space_id, id)
        ON DELETE SET NULL (spool_id);

