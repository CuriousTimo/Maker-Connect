-- Permissions on machines (crate::access): today's tables and columns, on Postgres (hub-core-v2.md §3,
-- "Step 2's tables"). Ids keep their types (INTEGER → bigint, machine ids text); times are timestamptz
-- through at_unix()/unix_seconds() (store/migrations). Every table carries space_id with row-level security
-- on app_space(). Transitional (lanes 2-3): machines are still on SQLite, so machine_id is plain text here,
-- without a foreign key; user ids are without one, as today.

CREATE TABLE machine_grants (
    space_id bigint NOT NULL REFERENCES spaces (id),
    machine_id text NOT NULL,
    user_id bigint NOT NULL,
    level text NOT NULL,
    granted_by bigint,
    granted_at timestamptz NOT NULL,
    expires_at timestamptz,
    PRIMARY KEY (machine_id, user_id)
);
CREATE INDEX machine_grants_by_space ON machine_grants (space_id, user_id);

-- Groups of machines (3D printers, say): permission on a group is permission on every machine in it, also
-- on those added later.
CREATE TABLE machine_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    name text NOT NULL,
    created_at timestamptz NOT NULL,
    UNIQUE (id, space_id)
);

CREATE TABLE machine_group_members (
    space_id bigint NOT NULL,
    group_id bigint NOT NULL,
    machine_id text NOT NULL,
    PRIMARY KEY (group_id, machine_id),
    FOREIGN KEY (group_id, space_id) REFERENCES machine_groups (id, space_id)
);
CREATE INDEX machine_group_members_by_machine ON machine_group_members (machine_id);

-- Someone asks the staff for permission (or a training) on a machine.
CREATE TABLE access_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    user_id bigint NOT NULL,
    machine_id text NOT NULL,
    asked_at timestamptz NOT NULL,
    state text NOT NULL DEFAULT 'open',
    handled_by bigint,
    handled_at timestamptz
);
CREATE INDEX access_requests_by_space ON access_requests (space_id, state);

CREATE TABLE group_grants (
    space_id bigint NOT NULL,
    group_id bigint NOT NULL,
    user_id bigint NOT NULL,
    level text NOT NULL,
    granted_by bigint,
    granted_at timestamptz NOT NULL,
    expires_at timestamptz,
    PRIMARY KEY (group_id, user_id),
    FOREIGN KEY (group_id, space_id) REFERENCES machine_groups (id, space_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE
    ON machine_grants, machine_groups, machine_group_members, access_requests, group_grants
    TO maker_connect_app;
ALTER TABLE machine_grants ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON machine_grants USING (space_id = app_space());
ALTER TABLE machine_groups ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON machine_groups USING (space_id = app_space());
ALTER TABLE machine_group_members ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON machine_group_members USING (space_id = app_space());
ALTER TABLE access_requests ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON access_requests USING (space_id = app_space());
ALTER TABLE group_grants ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON group_grants USING (space_id = app_space());
