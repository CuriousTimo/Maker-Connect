-- Times (wiki Design: Devices and Rights, "Times"): when the space is open and when a group gives its
-- right, in the space's time zone. One model for both: a window is days of the week and a span of the
-- day. No windows for the space: always open; none for a group: its right at all times. Closed days
-- (holidays, vacations) close the space whole days. The hub checks at Open and Start only; owners and
-- admins always pass.

-- The space's time zone, IANA ("Europe/Amsterdam").
ALTER TABLE spaces ADD COLUMN time_zone text NOT NULL DEFAULT 'Europe/Amsterdam';

CREATE TABLE time_windows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    -- NULL: the space's opening hours; else the group's window.
    group_id bigint,
    -- Days of the week, Monday bit 0 ... Sunday bit 6.
    days integer NOT NULL CHECK (days > 0 AND days < 128),
    -- Minutes from midnight: from (in) to (out).
    starts_min integer NOT NULL CHECK (starts_min >= 0),
    ends_min integer NOT NULL CHECK (ends_min <= 1440 AND ends_min > starts_min),
    FOREIGN KEY (group_id, space_id) REFERENCES machine_groups (id, space_id)
);
CREATE INDEX time_windows_by_space ON time_windows (space_id, group_id);

CREATE TABLE closed_days (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    first_day date NOT NULL,
    last_day date NOT NULL CHECK (last_day >= first_day),
    name text NOT NULL
);
CREATE INDEX closed_days_by_space ON closed_days (space_id, last_day);

GRANT SELECT, INSERT, UPDATE, DELETE ON time_windows, closed_days TO maker_connect_app;
ALTER TABLE time_windows ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON time_windows USING (space_id = app_space());
ALTER TABLE closed_days ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON closed_days USING (space_id = app_space());
