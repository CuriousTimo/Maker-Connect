-- Guides (crate::guides, wiki Design: Guides): step-by-step instructions per space. A guide's content
-- (title, difficulty, steps with lines and photos) is one document, maker_connect_guides::Guide as JSON:
-- `draft` is what the editor saves, `published` what readers see (none: not published yet). Photos are
-- files in the hub's guides folder, named in the document. Row-level security on app_space().

CREATE TABLE guides (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces (id),
    draft jsonb NOT NULL,
    published jsonb,
    author text NOT NULL,
    last_editor text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    published_at timestamptz,
    UNIQUE (space_id, id)
);
CREATE INDEX guides_by_space ON guides (space_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON guides TO maker_connect_app;
ALTER TABLE guides ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON guides USING (space_id = app_space());
