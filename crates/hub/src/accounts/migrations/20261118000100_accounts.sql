-- Accounts and tenancy (crate::accounts, crate::access): today's tables and columns, on Postgres
-- (hub-core-v2.md §3, "Step 2's tables"). Ids keep their types (INTEGER → bigint), times stay Unix seconds.
-- Tenant tables carry space_id and row-level security on app_space(); instance-wide ones (users, identities,
-- sessions) are reached by the admin role only where sign-in needs them, and joined for names.

CREATE TABLE organisations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid text NOT NULL UNIQUE,
    name text NOT NULL,
    created_at bigint NOT NULL
);

CREATE TABLE spaces (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    uid text NOT NULL UNIQUE,
    -- Ask for PPE before a machine is used (crate::safety): for a makerspace, not at home.
    ppe_checks boolean NOT NULL DEFAULT false,
    -- The example files went in once (crate::samples).
    samples_given boolean NOT NULL DEFAULT false,
    organisation_id bigint NOT NULL REFERENCES organisations (id)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    display_name text NOT NULL,
    instance_admin boolean NOT NULL DEFAULT false,
    disabled boolean NOT NULL DEFAULT false,
    created_at bigint NOT NULL
);
-- Names are the same whatever their case (SQLite's COLLATE NOCASE: ASCII letters only, as names are ASCII).
CREATE UNIQUE INDEX users_by_name ON users (lower(name));

CREATE TABLE identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    provider text NOT NULL,
    subject text NOT NULL,
    secret text,
    created_at bigint NOT NULL,
    UNIQUE (provider, subject)
);

CREATE TABLE memberships (
    user_id bigint NOT NULL REFERENCES users (id),
    space_id bigint NOT NULL REFERENCES spaces (id),
    role text NOT NULL,
    created_at bigint NOT NULL,
    PRIMARY KEY (user_id, space_id)
);
CREATE INDEX memberships_by_space ON memberships (space_id);

CREATE TABLE org_memberships (
    user_id bigint NOT NULL REFERENCES users (id),
    organisation_id bigint NOT NULL REFERENCES organisations (id),
    role text NOT NULL,
    created_at bigint NOT NULL,
    PRIMARY KEY (user_id, organisation_id)
);

CREATE TABLE sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash text NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES users (id),
    space_id bigint REFERENCES spaces (id),
    created_at bigint NOT NULL,
    last_seen bigint NOT NULL,
    expires_at bigint NOT NULL,
    user_agent text NOT NULL DEFAULT '',
    address text NOT NULL DEFAULT ''
);
CREATE INDEX sessions_by_user ON sessions (user_id);

CREATE TABLE invites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash text NOT NULL UNIQUE,
    space_id bigint NOT NULL REFERENCES spaces (id),
    role text NOT NULL,
    created_by bigint NOT NULL REFERENCES users (id),
    created_at bigint NOT NULL,
    expires_at bigint NOT NULL,
    used_by bigint REFERENCES users (id),
    used_at bigint,
    revoked boolean NOT NULL DEFAULT false,
    -- Into the whole organisation of the space (all its spaces), or this space only.
    whole_organisation boolean NOT NULL DEFAULT true
);

CREATE TABLE api_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash text NOT NULL UNIQUE,
    space_id bigint NOT NULL REFERENCES spaces (id),
    created_by bigint NOT NULL REFERENCES users (id),
    name text NOT NULL,
    role text NOT NULL,
    created_at bigint NOT NULL,
    last_used bigint,
    revoked boolean NOT NULL DEFAULT false
);

CREATE TABLE audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL,
    at bigint NOT NULL,
    user_id bigint,
    token_id bigint,
    actor text NOT NULL,
    action text NOT NULL,
    target text NOT NULL DEFAULT '',
    detail text NOT NULL DEFAULT ''
);
CREATE INDEX audit_by_space ON audit_log (space_id, at);

-- Row-level security: a request's transaction sees only its space's rows (and its organisation's).
ALTER TABLE spaces ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON spaces USING (id = app_space());
ALTER TABLE organisations ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON organisations
    USING (id = (SELECT s.organisation_id FROM spaces s WHERE s.id = app_space()));
ALTER TABLE org_memberships ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON org_memberships
    USING (organisation_id = (SELECT s.organisation_id FROM spaces s WHERE s.id = app_space()));
ALTER TABLE memberships ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON memberships USING (space_id = app_space());
ALTER TABLE invites ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON invites USING (space_id = app_space());
ALTER TABLE api_tokens ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON api_tokens USING (space_id = app_space());
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
CREATE POLICY in_space ON audit_log USING (space_id = app_space());

