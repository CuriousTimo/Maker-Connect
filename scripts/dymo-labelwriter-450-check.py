def tests_rows():
    """Every test case of the driver's own test files, and the Rust test that ports it."""
    rs = open(os.path.join(PORT, "tests.rs")).read().split("\n")
    rows, missing = [], []
    for path in TEST_FILES:
        for n, line in enumerate(open(os.path.join(REF, path), encoding="latin-1").read().split("\n"), 1):
            m = re.match(r"^(\w+)::(test\w+)\(\)", line)
            if not m:
                continue
            q = m.group(1) + "::" + m.group(2)
            if q in TESTS_NOT_PORTED:
                rows.append((path, n, q, None, TESTS_NOT_PORTED[q]))
                continue
            found = None
            for i, l in enumerate(rs, 1):
                if l.startswith("/// `" + q + "`"):
                    # the fn name on the next non-attribute line
                    for j in range(i, min(i + 4, len(rs))):
                        mm = re.match(r"fn (\w+)", rs[j])
                        if mm:
                            found = (mm.group(1), i)
                            break
                    break
            if found:
                rows.append((path, n, q, found, None))
            else:
                missing.append((path, n, q))
    return rows, missing


def generated_audit_blocks():
    rows, missing = coverage_rows()
    trows, tmissing = tests_rows()
    if tmissing:
        raise SystemExit("tests not ported and not listed: " + ", ".join(f"{p}:{n} {q}" for p, n, q in tmissing))
    if missing:
        raise SystemExit("not in the port and not listed as not ported: " + ", ".join(f"{p}:{n} {q}" for p, n, q in missing))
    o = ["| Driver function | Line | The port | Result |", "|---|---|---|---|"]
    ported = 0
    for path, n, q, found, why in rows:
        if why and why.startswith("ported"):
            ported += 1
            o.append(f"| `{q}` | `{path}:{n}` | {why} | ported |")
        elif found:
            ported += 1
            o.append(f"| `{q}` | `{path}:{n}` | `crates/engine/src/ports/dymo_cups/{found}` | ported (tested in section 2, proved in section 3) |")
        else:
            o.append(f"| `{q}` | `{path}:{n}` | not ported: {why} | not covered |")
    o.append("")
    o.append(f"{ported} functions ported, {len(rows) - ported} listed as not ported (of {len(rows)} in the {len(FILES)} files).")
    t = ["| Driver test | Line | The port's test (`crates/engine/src/ports/dymo_cups/tests.rs`) | Result |", "|---|---|---|---|"]
    tp = 0
    for path, n, q, found, why in trows:
        if found:
            tp += 1
            t.append(f"| `{q}` | `{path}:{n}` | `{found[0]}` (:{found[1]}) | **passes** |")
        else:
            t.append(f"| `{q}` | `{path}:{n}` | not ported: {why} | not covered |")
    t.append("")
    t.append(f"{tp} of {len(trows)} test cases ported ({len(trows) - tp} not covered).")
    return {"functions": "\n".join(o), "tests": "\n".join(t)}


def audit_check_or_write(write):
    blocks = generated_audit_blocks()
    text = open(AUDIT).read() if os.path.exists(AUDIT) else ""
    new = text
    for name, block in blocks.items():
        begin, end = f"<!-- generated {name}: begin -->", f"<!-- generated {name}: end -->"
        if begin not in new or end not in new:
            print(f"FAIL: the audit has no generated block `{name}`")
            return False
        head, rest = new.split(begin, 1)
        _, tail = rest.split(end, 1)
        new = head + begin + "\n" + block + "\n" + end + tail
    if write:
        open(AUDIT, "w").write(new)
        print("wrote the generated blocks of", AUDIT)
        return True
    if new != text:
        print("FAIL: the generated blocks of the audit differ from the sources (run `audit`)")
        return False
    print("ok: the audit's tables of driver functions and tests are what the sources give")
    return True


