def proof():
    """Builds DYMO's raster2dymolw and a helper on libcups, makes the pages with CUPS's own header code and
    compares what the real filter writes with what the port writes (stdout bytes and stderr lines)."""
    work = tempfile.mkdtemp(prefix=f"dymo-{STEM}-proof-")
    target = os.environ.get("CARGO_TARGET_DIR", "target")
    example = os.path.join(ROOT, target, "debug", "examples", "dymo_cups_proof")
    if not os.path.exists(example):
        print("build the example first: cargo build -p maker-connect-engine --example dymo_cups_proof")
        return 2
    pre = os.path.join(work, "pre.h")
    open(pre, "w").write("#include <cups/cups.h>\n#include <cups/ppd.h>\n#include <cups/raster.h>\n#include <cups/backend.h>\n#include <cups/sidechannel.h>\n")
    lw, common = os.path.join(REF, "src", "lw"), os.path.join(REF, "src", "common")
    real = os.path.join(work, "raster2dymolw")
    srcs = [os.path.join(lw, f) for f in ("raster2dymolw.cpp", "LabelWriterDriver.cpp", "LabelWriterLanguageMonitor.cpp", "CupsFilterLabelWriter.cpp")] + [
        os.path.join(common, f) for f in ("CupsPrintEnvironment.cpp", "DummyLanguageMonitor.cpp", "Halftoning.cpp", "ErrorDiffusionHalftoning.cpp", "NonLinearLaplacianHalftoning.cpp")]
    r = run(["clang++", "-std=c++98", "-w", "-include", pre, "-I" + common, "-I" + lw, "-o", real] + srcs + ["-lcups"])
    if r.returncode:
        print("cannot build raster2dymolw:", r.stderr.decode()[:2000])
        return 2
    mkras = os.path.join(work, "mkras")
    r = run(["clang", "-w", "-o", mkras, os.path.join(ROOT, "scripts", "dymo-labelwriter-450", "mkras.c"), "-lcups"])
    if r.returncode:
        print("cannot build mkras:", r.stderr.decode()[:2000])
        return 2

    model, options, sizes, reasons = parse_ppd()
    size_names = [c[0] for c in [o for o in options if o[0] == "PageSize"][0][4]]
    ok = True

    def length_mm(name):
        # the port's rule (W2): the PaperDimension length in mm, rounded half away from zero
        return int(sizes[name]["paper"][0][1] * 25.4 / 72 + 0.5)

    def without_name(hdr):
        # `cupsPageSizeName` is not read by the filter; the PPD has several choices of the same page
        # (`w72h72`, `w72h72.1`, ...) and the port takes the first
        return re.sub(r"^name=\S+ ", "", hdr)

    # 1. the page header of every PageSize choice: CUPS's (libcups on the PPD) against the port's
    head_ok = 0
    same_page_other_name = 0
    named_page = 0
    for name in size_names:
        out = os.path.join(work, "h-" + name)
        os.makedirs(out)
        w, h = [int(x) for x in run([mkras, "dims", PPD, "PageSize=" + name]).stdout.split()]
        png = os.path.join(out, "p.png")
        write_png(png, w, h, None)
        o = run([example, png, str(length_mm(name)), "", "ipp://x", "-", out, MODEL])
        if os.path.exists(os.path.join(out, "ours.page-error")):
            err = open(os.path.join(out, "ours.page-error")).read()
            if "several labels" in err:
                # two different pages of the same length and picture size: the length cannot choose; the
                # job names its page (W2b, as CUPS's `-o PageSize=<name>`)
                named_page += 1
                os.remove(os.path.join(out, "ours.page-error"))
                o = run([example, png, "ps:" + name, "", "ipp://x", "-", out, MODEL])
        if os.path.exists(os.path.join(out, "ours.page-error")):
            err = open(os.path.join(out, "ours.page-error")).read()
            print("FAIL header", name, err)
            ok = False
            continue
        pix = os.path.join(out, "page.pixels")
        r = subprocess.run([mkras, "ras", PPD, "PageSize=" + name, pix], capture_output=True)
        real_hdr = r.stderr.decode().strip()
        ours_hdr = open(os.path.join(out, "ours.header")).read().strip()
        if without_name(real_hdr) != without_name(ours_hdr):
            print("FAIL header", name, "\n  real:", real_hdr, "\n  ours:", ours_hdr)
            ok = False
        else:
            head_ok += 1
            if real_hdr != ours_hdr:
                same_page_other_name += 1
        subprocess.run(["rm", "-rf", out])
    print(f"headers: {head_ok} of {len(size_names)} PageSize choices identical (CUPS's libcups vs the port), {same_page_other_name} of them under the name of an earlier choice of the same page, {named_page} named by the job (W2b: the length is not unique)")

    # 2. the bytes: the real filter against the port, on the same pages
    cases = CASES
    byte_ok = 0
    for title, name, opts, status, uri in cases:
        out = os.path.join(work, "c-" + re.sub(r"\W+", "_", title))
        os.makedirs(out)
        w, h = [int(x) for x in run([mkras, "dims", PPD, (opts + " " if opts else "") + "PageSize=" + name]).stdout.split()]
        png = os.path.join(out, "p.png")
        write_png(png, w, h, (noise if title.startswith('noise') else picture)(w, h))
        ours = run([example, png, str(length_mm(name)), opts, uri or "-", status or "-", out, MODEL])
        if os.path.exists(os.path.join(out, "ours.page-error")) and "several labels" in open(os.path.join(out, "ours.page-error")).read():
            # the length is not unique for this page: the job names it (W2b)
            os.remove(os.path.join(out, "ours.page-error"))
            ours = run([example, png, "ps:" + name, opts, uri or "-", status or "-", out, MODEL])
            title += " (page named by the job)"
        if os.path.exists(os.path.join(out, "ours.page-error")):
            print("FAIL", title, "port could not make the page:", open(os.path.join(out, "ours.page-error")).read())
            ok = False
            continue
        # the options of the page: the size and the filter's options
        mk_opts = (opts + " " if opts else "") + "PageSize=" + name
        pix = os.path.join(out, "page.pixels")
        ras = os.path.join(out, "real.ras")
        subprocess.run([mkras, "ras", PPD, mk_opts, pix], stdout=open(ras, "wb"), stderr=subprocess.DEVNULL)
        env = dict(os.environ, PPD=PPD)
        env.pop("DEVICE_URI", None)
        if uri:
            env["DEVICE_URI"] = uri
        rfd, wfd = os.pipe()
        if status:
            os.write(wfd, bytes.fromhex(status))
        no_printer = title.startswith("no printer")
        if no_printer:
            # macOS's libcups `cupsBackChannelRead` ignores its timeout (it blocks until the pipe has data
            # or ends: measured), so the real filter is given a pipe that is at its end: its status reads
            # return at once and it spins to its 10 s limit. The port's reads wait 2.5 s as backchannel.c
            # says. The status loop therefore writes a different number of `ESC A` and debug lines: only the
            # label's bytes before and after the status requests and the exit status can be compared.
            os.close(wfd)

        def pre_exec(rfd=rfd):
            # the back channel is fd 3 (`cupsBackChannelRead`)
            if rfd != 3:
                os.dup2(rfd, 3)
            os.set_inheritable(3, True)

        p = subprocess.run([real, "1", "maker-connect", "proof", "1", opts], stdin=open(ras, "rb"), capture_output=True, env=env, preexec_fn=pre_exec, close_fds=False, timeout=300)
        os.close(rfd)
        if not no_printer:
            os.close(wfd)
        ours_bin = open(os.path.join(out, "ours.bin"), "rb").read()
        if no_printer:
            # drop the repeated status requests (`ESC A`) of the loops, which differ in number
            strip = lambda b: b.replace(b"\x1bA", b"")
            same_bytes = strip(p.stdout) == strip(ours_bin)
        else:
            same_bytes = p.stdout == ours_bin
        norm = lambda t: [l for l in t.splitlines() if "ReadStatus() " not in l or "returned" in l]
        real_err = norm(p.stderr.decode("latin-1"))
        ours_err = norm(open(os.path.join(out, "ours.err")).read())
        # the real filter reports `PageHeader.cups...` lines as the port does; the status of the exit too
        same_err = True if no_printer else real_err == ours_err
        same_status = p.returncode == int(open(os.path.join(out, "ours.status")).read())
        if same_bytes and same_err and same_status:
            byte_ok += 1
            print(f"identical: {title}: {len(ours_bin)} bytes, {len(real_err)} stderr lines")
        else:
            ok = False
            print(f"DIFFERENT: {title}: bytes {'same' if same_bytes else 'differ (%d vs %d)' % (len(p.stdout), len(ours_bin))}, stderr {'same' if same_err else 'differs'}, exit {'same' if same_status else 'differs'}")
            if not same_err:
                for a, b in zip(real_err, ours_err):
                    if a != b:
                        print("   real:", a[:150], "\n   ours:", b[:150])
                        break
                print("   lines real/ours:", len(real_err), len(ours_err))
        # keep the work directory only on a difference
        if same_bytes and same_err and same_status:
            subprocess.run(["rm", "-rf", out])
    print(f"bytes: {byte_ok} of {len(cases)} cases identical")
    if ok:
        subprocess.run(["rm", "-rf", work])
    else:
        print("work directory kept:", work)
    return 0 if ok else 1


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "proof":
        return proof()
    if cmd == "audit":
        return 0 if audit_check_or_write(True) else 1
    text = generate()
    if cmd == "gen":
        open(OUT, "w").write(text)
        print("wrote", OUT)
        return 0
    ok = True
    on_disk = open(OUT).read() if os.path.exists(OUT) else ""
    if on_disk != text:
        print("FAIL: ppd_lw450.rs differs from what lw450.ppd gives (run gen)")
        ok = False
    else:
        print("ok: ppd_lw450.rs is what lw450.ppd gives")
    fails = check_driver_source()
    for f in fails:
        print("FAIL:", f)
        ok = False
    if not fails:
        print("ok: the driver's source holds what the port relies on")
    if not audit_check_or_write(False):
        ok = False
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
