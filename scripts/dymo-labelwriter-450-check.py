def cpp_functions(path):
    """(qualified name, line) of every function definition of a C++ file: a name at column 0 followed by `(`,
    after a line that is a type, or `Class::Name(` / `Class<...>::Name(`."""
    lines = open(os.path.join(REF, path), encoding="latin-1").read().split("\n")
    out = []
    cls_re = re.compile(r"^(\w+)(?:<[^>]*>)?::(~?\w+)\s*\(")
    plain_re = re.compile(r"^(~?\w+)\s*\(")
    for n, line in enumerate(lines, 1):
        m = cls_re.match(line)
        if m:
            out.append((m.group(1) + "::" + m.group(2), n))
            continue
        m = plain_re.match(line)
        if m and n > 1:
            prev = lines[n - 2].strip()
            if prev and not prev.endswith((";", ",", ")", "{", "}")) and not prev.startswith(("//", "*", "/*", "#", "else", "if", "return", "case")) \
                    and m.group(1) not in ("if", "for", "while", "switch", "return", "assert", "fprintf", "fputs", "sizeof"):
                out.append((m.group(1), n))
    # the template methods of CupsFilter.h: `CCupsFilter<D, DI, LM>::Run(`
    return out


def rust_mentions():
    """name -> (rust file, line) of its doc comment: the first `///`/`//!` line that names the C++ item."""
    texts = {}
    for fn in sorted(os.listdir(PORT)):
        if fn.endswith(".rs") and fn not in ("tests.rs", "ppd_lw450.rs"):
            texts[fn] = open(os.path.join(PORT, fn)).read().split("\n")
    return texts


def coverage_rows():
    texts = rust_mentions()
    rows = []
    missing = []
    for path, rfiles in FILES:
        for q, n in cpp_functions(path):
            short = q.split("::")[-1]
            if f"{q}@{n}" in NOT_PORTED:
                rows.append((path, n, q, None, NOT_PORTED[f"{q}@{n}"]))
                continue
            if q in NOT_PORTED:
                rows.append((path, n, q, None, NOT_PORTED[q]))
                continue
            found = None
            # the doc line that names it and cites its lines: first one whose cite starts at the definition
            # (or the line before it, where the return type is), else the first that names it
            for strict in (True, False):
                for rf in rfiles:
                    for i, l in enumerate(texts[rf], 1):
                        m = re.search(r"`[\w:]*" + re.escape(short) + r"(?:\([^)]*\))?`\s*\(:(\d+)", l)
                        if l.lstrip().startswith(("///", "//!")) and m and (not strict or abs(int(m.group(1)) - n) <= 1):
                            found = f"{rf}:{i}"
                            break
                    if found:
                        break
                if found:
                    break
            if found:
                rows.append((path, n, q, found, None))
            else:
                missing.append((path, n, q))
    return rows, missing


