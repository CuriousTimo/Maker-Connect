def parse_ppd():
    lines = open(PPD, encoding="latin-1").read().split("\n")
    model = None
    options = []      # [keyword, text, default, default_line, [choices]]
    sizes = {}        # name -> dict
    reasons = []
    cur = None
    for n, line in enumerate(lines, 1):
        m = re.match(r'\*ModelName:\s*"(.*)"', line)
        if m:
            model = (m.group(1), n)
        m = re.match(r'\*cupsIPPReason (com\.dymo\.[^/]+)/(.*?) : ""', line)
        if m:
            reasons.append((m.group(1), m.group(2), n))
        m = re.match(r'\*OpenUI \*(\w+)/?([^:]*):\s*(\w+)', line)
        if m:
            cur = [m.group(1), m.group(2), None, 0, [], None, 0, None]
            options.append(cur)
            continue
        if line.startswith("*CloseUI"):
            cur = None
            continue
        if cur is not None:
            m = re.match(r'\*OrderDependency:\s*([\d.]+)\s+(\w+)\s+\*' + cur[0] + r'\s*$', line)
            if m:
                cur[5], cur[7], cur[6] = float(m.group(1)), m.group(2), n
                continue
            m = re.match(r'\*Default' + cur[0] + r':\s*(\S+)', line)
            if m:
                cur[2], cur[3] = m.group(1), n
                continue
            m = re.match(r'\*' + cur[0] + r' (\S+?)(?:/([^:]*))?: "(.*)"', line)
            if m:
                cur[4].append((m.group(1), m.group(3), n, m.group(2)))
        m = re.match(r'\*ImageableArea (\S+?)(?:/[^:]*)?: "([\d. ]+)"', line)
        if m:
            sizes.setdefault(m.group(1), {})["imageable"] = ([float(x) for x in m.group(2).split()], n)
        m = re.match(r'\*PaperDimension (\S+?)(?:/[^:]*)?: "([\d. ]+)"', line)
        if m:
            sizes.setdefault(m.group(1), {})["paper"] = ([float(x) for x in m.group(2).split()], n)
    return model, options, sizes, reasons


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    model, options, sizes, reasons = parse_ppd()
    # the PPD's own notice, `*% Copyright (C) <year> Sanford L.P.` (:6)
    year = re.search(r"Copyright \(C\) (\d+) Sanford", open(PPD, encoding="latin-1").read().split("\n")[5]).group(1)
    rl = f"{min(r[2] for r in reasons)}-{max(r[2] for r in reasons)}"
    o = []
    o.append(f"// GENERATED by scripts/{GEN}-check.py gen from {PPD_NAME}.")
    o.append("// Do not edit: `check` fails if this file differs from what the PPD gives.")
    o.append("//")
    o.append(f"// DYMO LabelWriter Drivers, Copyright (C) {year} Sanford L.P. (the PPD's own notice, {STEM}.ppd:5-20): GPL-2 or")
    o.append("// any later version, taken as GPL-3 so it combines with this program's AGPL-3.0.")
    o.append("")
    o.append(f"//! The {DESC}'s PPD (`ppd/{STEM}.ppd`): the values the filter and CUPS's option marking read,")
    o.append("//! each with its line in that file (`line`, `*_line`).")
    o.append("")
    o.append("use super::ppd::{Choice, OptionData, SizeData};")
    o.append("")
    o.append(f"/// `*ModelName` ({STEM}.ppd:{model[1]}): what `raster2dymolw.cpp:78-115` matches.")
    o.append(f"pub const MODEL_NAME: &str = {rust_str(model[0])};")
    o.append("")
    o.append(f"/// `*cupsIPPReason` ({STEM}.ppd:{rl}): the reason keyword, its English text, its line.")
    o.append("pub const REASONS: &[(&str, &str, u32)] = &[")
    for k, t, n in reasons:
        o.append(f"    ({rust_str(k)}, {rust_str(t)}, {n}),")
    o.append("];")
    o.append("")
    o.append("/// The options of the PPD in file order (`*OpenUI`), with their default choice and their choices.")
    o.append("pub static OPTIONS: &[OptionData] = &[")
    for kw, text, dflt, dl, chs, order, order_line, section in options:
        o.append("    OptionData {")
        o.append(f"        keyword: {rust_str(kw)},")
        o.append(f"        default_choice: {rust_str(dflt)},")
        o.append(f"        default_line: {dl},")
        o.append(f"        order: {order!r},")
        o.append(f"        order_line: {order_line},")
        o.append(f"        section: {rust_str(section)},")
        o.append("        choices: &[")
        for name, code, n, text in chs:
            t = "None" if text is None else f"Some({rust_str(text)})"
            o.append(f"            Choice {{ name: {rust_str(name)}, text: {t}, code: {rust_str(code)}, line: {n} }},")
        o.append("        ],")
        o.append("    },")
    o.append("];")
    o.append("")
    o.append("/// The `PageSize` choices with what the PPD says of each: `PaperDimension` and `ImageableArea` (points).")
    o.append("pub static SIZES: &[SizeData] = &[")
    ps = [x for x in options if x[0] == "PageSize"][0]
    for name, code, n, _text in ps[4]:
        m = re.search(r'/PageSize\[(\d+) (\d+)\]', code)
        mt = re.search(r'/cupsMediaType (\d+)', code)
        ci = re.search(r'/cupsInteger0 (-?\d+)', code)
        s = sizes[name]
        ia, ial = s["imageable"]
        pd, pdl = s["paper"]
        o.append("    SizeData {")
        o.append(f"        name: {rust_str(name)},")
        o.append(f"        page_size_line: {n},")
        o.append(f"        page_size: [{m.group(1)}, {m.group(2)}],")
        o.append(f"        cups_media_type: {mt.group(1) if mt else 0},")
        o.append(f"        cups_integer0: {ci.group(1) if ci else 0},")
        o.append(f"        imageable_area_line: {ial},")
        o.append(f"        imageable_area: [{', '.join(repr(v) for v in ia)}],")
        o.append(f"        paper_dimension_line: {pdl},")
        o.append(f"        paper_dimension: [{', '.join(repr(v) for v in pd)}],")
        o.append("    },")
    o.append("];")
    o.append("")
    return "\n".join(o)


def check_driver_source():
    """What the port relies on in the driver's own source, found in it."""
    def src(p):
        return open(os.path.join(REF, p), encoding="latin-1").read()
    fails = []
    flt = src("src/common/CupsFilter.h")
    lwf = src("src/lw/CupsFilterLabelWriter.cpp")
    mon = src("src/lw/LabelWriterLanguageMonitor.cpp")
    main = src("src/lw/raster2dymolw.cpp")
    env = src("src/common/CupsPrintEnvironment.cpp")
    # the header fields the filter and the initializers read (and cupsWidth is not read)
    fields = set(re.findall(r'PageHeader\.(\w+)', flt + lwf))
    want = {"cupsBytesPerLine", "cupsBitsPerColor", "cupsBitsPerPixel", "cupsColorOrder", "cupsHeight",
            "cupsMediaType", "PageSize", "HWResolution", "cupsInteger"}
    if fields != want:
        fails.append(f"header fields read: {sorted(fields)} != {sorted(want)}")
    if "cupsWidth" in flt + lwf + mon:
        fails.append("cupsWidth is read")
    # the resolution trap: only 203dpi and 203x138dpi are matched
    if re.findall(r'strcasecmp\(choice->choice, "([^"]+dpi)"\)', lwf) != ["203dpi", "203x138dpi"]:
        fails.append("resolution choices matched are not 203dpi/203x138dpi")
    # the 450's model name takes CLabelWriterDriver400 with the language monitor
    if '"DYMO LabelWriter 450"' not in main:
        fails.append("model name DYMO LabelWriter 450 not in raster2dymolw.cpp")
    # the monitor skips the status unless usb://
    if 'strncmp(uri, "usb://", 6) == 0' not in mon:
        fails.append("usb:// test not in the monitor")
    # the back channel read
    if "cupsBackChannelRead((char*)buf, sizeof(buf), 2.5)" not in env:
        fails.append("cupsBackChannelRead(buf, 16, 2.5) not in CupsPrintEnvironment.cpp")
    if "size_t ReadStatusTimeout = 10" not in src("src/lw/LabelWriterLanguageMonitor.h"):
        fails.append("ReadStatusTimeout 10 not in the monitor header")
    return fails



