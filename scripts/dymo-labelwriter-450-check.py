import struct, subprocess, tempfile, zlib


def write_png(path, w, h, pixel):
    """An 8-bit RGB PNG; `pixel(x, y)` gives (r, g, b), or None for an all-white picture."""
    rows = []
    for y in range(h):
        if pixel is None:
            rows.append(b"\0" + b"\xff" * (3 * w))
        else:
            rows.append(b"\0" + b"".join(bytes(pixel(x, y)) for x in range(w)))
    raw = b"".join(rows)

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    open(path, "wb").write(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 1))
        + chunk(b"IEND", b"")
    )


def picture(w, h):
    """A deterministic test picture: a frame, lines, a text-like block, a grey ramp, a dark blob, and the
    colours (so that the halftoning has black, white, greys and colours to work on)."""
    def px(x, y):
        if x < 6 or y < 6 or x >= w - 6 or y >= h - 6:
            return (0, 0, 0)
        if (x // 7 + y // 11) % 9 == 0 and x > w // 4:
            return (0, 0, 0)
        if y > h // 2 and y < h // 2 + 40:
            g = 255 * x // max(1, w - 1)
            return (g, g, g)
        if y > h // 2 + 60 and y < h // 2 + 80:
            return ((x * 3) % 256, (x * 7) % 256, (x * 11) % 256)
        if (x - w // 3) ** 2 + (y - h // 3) ** 2 < (min(w, h) // 6) ** 2:
            return (40, 40, 40)
        return (255, 255, 255)
    return px


def noise(w, h):
    """Pseudo-random greys and colours (a fixed linear congruential generator), with runs of black and
    white: the halftoning's error terms get every value."""
    def px(x, y):
        v = (x * 7919 + y * 104729 + (x * y) % 977) * 2654435761 % 4294967296
        k = (v >> 8) % 11
        if k == 0:
            return (0, 0, 0)
        if k == 1:
            return (255, 255, 255)
        if k < 6:
            g = (v >> 16) % 256
            return (g, g, g)
        return ((v >> 4) % 256, (v >> 12) % 256, (v >> 20) % 256)
    return px


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, **kw)


