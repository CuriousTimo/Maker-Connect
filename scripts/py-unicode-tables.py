#!/usr/bin/env python3
"""Generate crates/gcode-metadata/src/py_unicode.rs from the running CPython.

The tables are Python's own character predicates, as CPython 3.13 applies them:
`str.isspace` (also `str.strip()`, and the spaces `int()`/`float()` skip), `str.isalpha`,
`str.isdecimal` with its digit value (`int()`, `float()`, and `\\d` of `re` on `str`),
`str.isalnum` or `_` (`\\w` of `re` on `str`) and `str.isprintable` (`repr(str)`).

Run it with the project's CPython 3.13 venv; `--check` fails when the file is not what this
Python generates:

    reference/.venv-connect-sdk-313/bin/python -I scripts/py-unicode-tables.py [--check]
"""

import sys
import unicodedata
from pathlib import Path

OUT = (Path(__file__).resolve().parent.parent / "crates" / "gcode-metadata" / "src" /
       "py_unicode.rs")


def ranges(pred):
    """Inclusive (first, last) code point runs where `pred(char)` holds."""
    result = []
    start = None
    for code in range(sys.maxunicode + 2):
        hit = code <= sys.maxunicode and pred(chr(code))
        if hit and start is None:
            start = code
        elif not hit and start is not None:
            result.append((start, code - 1))
            start = None
    return result


def decimal_runs():
    """(first, last, value of first) runs of `str.isdecimal` with consecutive values."""
    result = []
    for code in range(sys.maxunicode + 1):
        char = chr(code)
        if not char.isdecimal():
            continue
        value = unicodedata.decimal(char)
        if result:
            first, last, first_value = result[-1]
            if code == last + 1 and value == first_value + (code - first):
                result[-1] = (first, code, first_value)
                continue
        result.append((code, code, value))
    return result


def table(name, runs, doc):
    lines = [f"/// {doc}", f"pub static {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in runs]
    lines.append("];")
    return "\n".join(lines)


def generate():
    version = sys.version.split()[0]
    parts = [
        "//! Python's character predicates, generated by `scripts/py-unicode-tables.py` from",
        f"//! CPython {version} (Unicode {unicodedata.unidata_version}). Do not edit by hand.",
        "",
        f'pub const PYTHON_VERSION: &str = "{version}";',
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        table("ISSPACE", ranges(str.isspace), "`str.isspace`"),
        "",
        table("ISALPHA", ranges(str.isalpha), "`str.isalpha`"),
        "",
        table("WORD", ranges(lambda c: c.isalnum() or c == "_"),
              "`\\w` of `re` on `str`: `str.isalnum()` or `_`"),
        "",
        table("ISPRINTABLE", ranges(str.isprintable),
              "`str.isprintable` (what `repr(str)` leaves unescaped)"),
        "",
        "/// `str.isdecimal`: (first, last, digit value of first), the values consecutive",
        "pub static DECIMAL: &[(u32, u32, u8)] = &[",
    ]
    parts += [f"    (0x{a:04X}, 0x{b:04X}, {v})," for a, b, v in decimal_runs()]
    parts += ["];", ""]
    return "\n".join(parts)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} differs from what CPython {sys.version.split()[0]} generates")
            return 1
        print(f"{OUT.name}: identical to CPython {sys.version.split()[0]}")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
