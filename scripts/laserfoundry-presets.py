#!/usr/bin/env python3
"""The hub's laser profiles from LaserFoundry's own preset list (owner, 2026-11-17: "ja, gebruik de lijst van
LaserFoundry"). LaserFoundry is the laser stack's one reference (docs/archive/plans/agent-engine.md, owner 2026-11-15).

  gen    writes profiles/<brand>/<model>.toml for every preset in LaserFoundry's
         crates/ui-egui/data/laser-presets.json, at the revision Cargo.lock pins (cargo metadata finds it)
  check  regenerates them in memory and fails if a file on disk differs (the default)

Each value is the preset's (as LaserFoundry read it from the maker's own page, its `source`): the bed
(`bed_width` × `bed_height` → `build_volume_mm`), the optical power (`optical_watts` → `laser_w`, left out
when the preset has none). `firmware = "grbl"`: LaserFoundry drives every preset with its default protocol,
GRBL (its presets name no other). Nothing else is written (no speed, no origin: the preset has none).

Run with `python3 -I`. Standard library and `cargo` only."""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROFILES = os.path.join(ROOT, "profiles")
# The brand's folder in profiles/ (ours, matching the folders the hub already has).
BRAND_DIR = {"xTool": "xtool", "Creality": "creality", "Ortur": "ortur", "Sculpfun": "sculpfun",
             "AtomStack": "atomstack", "TwoTrees": "two-trees", "NEJE": "neje", "Longer": "longer"}
# Presets that are a profile the hub already had under another file name (kept, so machines keep it).
KEEP_ID = {"Ortur Laser Master 3 (10W module)": "lm3", "Creality Falcon2 22W": "falcon2-22w",
           "Ortur Laser Master 2 Pro S2 (10W module)": "lm2-pro-s2"}


def presets_file():
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1"], cwd=ROOT,
                                     capture_output=True, check=True).stdout)
    device = next(p for p in meta["packages"] if p["name"] == "laserfoundry-device")
    root = os.path.dirname(os.path.dirname(os.path.dirname(device["manifest_path"])))
    rev = os.path.basename(root)
    return os.path.join(root, "crates", "ui-egui", "data", "laser-presets.json"), rev


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def files():
    path, rev = presets_file()
    data = json.load(open(path))
    out = {}
    for p in data["presets"]:
        brand, _, model = p["name"].partition(" ")
        folder = BRAND_DIR[brand]
        name = KEEP_ID.get(p["name"], slug(model))
        lines = [
            f"# GENERATED by scripts/laserfoundry-presets.py from LaserFoundry {rev}",
            "# (crates/ui-egui/data/laser-presets.json). Do not edit: `check` fails if this differs.",
            f"# LaserFoundry's source: {p['source']}",
            "# The controller tells its real travel ($130, $131) once it connects.",
            f'brand = "{brand}"',
            f'model = "{model}"',
            'kind = "laser"',
            f"build_volume_mm = [{p['bed_width']}, {p['bed_height']}, 0]",
            'firmware = "grbl"',
        ]
        if p.get("optical_watts") is not None:
            lines.append(f"laser_w = {p['optical_watts']}")
        out[os.path.join(PROFILES, folder, name + ".toml")] = "\n".join(lines) + "\n"
    return out


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    want = files()
    if cmd == "gen":
        for path, text in want.items():
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
            print("wrote", os.path.relpath(path, ROOT))
        return 0
    bad = [p for p, t in want.items() if not os.path.exists(p) or open(p).read() != t]
    for p in bad:
        print("FAIL:", os.path.relpath(p, ROOT), "differs from LaserFoundry's preset (run gen)")
    if not bad:
        print(f"ok: {len(want)} laser profiles are LaserFoundry's presets")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
