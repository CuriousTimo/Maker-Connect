#!/usr/bin/env python3
"""Generate crates/engine/src/ports/prusalink/unidecode_data.rs from the Unidecode package that
PrusaLink uses (`unidecode~=1.3.6` in `reference/Prusa-Link/requirements.txt`; the project's
PrusaLink venv has 1.3.8).

Every section `x0NN` of the package is copied as it is (`None` entries stay `None`).
`--check` fails when the file is not what the package generates:

    reference/.venv-prusalink/bin/python -I scripts/prusalink-unidecode-tables.py [--check]
"""

import importlib
import importlib.metadata
import pkgutil
import sys
from pathlib import Path

import unidecode

OUT = (Path(__file__).resolve().parent.parent / "crates" / "engine" / "src" / "ports" /
       "prusalink" / "unidecode_data.rs")


def lit(text):
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % code)
    out.append('"')
    return "".join(out)


def main():
    version = importlib.metadata.version("Unidecode")
    sections = []
    for info in pkgutil.iter_modules(unidecode.__path__):
        name = info.name
        if len(name) == 4 and name[0] == "x" and all(c in "0123456789abcdef" for c in name[1:]):
            mod = importlib.import_module("unidecode." + name)
            sections.append((int(name[1:], 16), mod.data))
    sections.sort()
    lines = [
        f"//! The transliteration tables of Unidecode {version} (GPL-2.0-or-later, Tomaz Solc),",
        "//! the package PrusaLink uses, generated by `scripts/prusalink-unidecode-tables.py`.",
        "//! Do not edit by hand.",
        "",
        f'pub const UNIDECODE_VERSION: &str = "{version}";',
        "",
        "/// `unidecode.xNNN.data` per section (`codepoint >> 8`), `None` for a `None` entry.",
        "#[rustfmt::skip]",
        "pub static SECTIONS: &[(u16, &[Option<&str>])] = &[",
    ]
    for section, data in sections:
        entries = ", ".join("None" if e is None else "Some(" + lit(e) + ")" for e in data)
        lines.append(f"    (0x{section:03x}, &[{entries}]),")
    lines.append("];")
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is not what the package generates")
        print("unidecode_data.rs is as generated")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}: {len(sections)} sections")


main()
